#!/usr/bin/env python3
# =============================================================================
# DRYAS  |  Script 010  —  ITRDB DATASET CITATIONS FROM NOAA METADATA
# =============================================================================
# WHAT THIS SCRIPT DOES
#   For every NOAA study ID in data/site_metadata.parquet (landing_page column),
#   fetches the study metadata from the NOAA Paleo Data Search API
#   (search.json?NOAAStudyId=<id>), extracts the study title, the originators,
#   the dataset DOI and the contribution date, and writes:
#     manuscript/itrdb_dataset_citations.md   Elsevier-Harvard [dataset] entries
#     manuscript/itrdb_dataset_citations.csv  the raw fields
#   Entries follow the journal's data-reference format:
#     Originators, Year. [dataset] Title. NOAA National Centers for Environmental
#     Information. https://doi.org/<DOI> (accessed <date>).
#   Nothing is invented: any field the API does not return is left as 【?】.
#
# USAGE   uv run python src/010_dataset_citations.py   (needs internet)
# =============================================================================

from __future__ import annotations

import json
import re
import sys
from datetime import date
from pathlib import Path

import pandas as pd
import requests

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
MS_DIR = ROOT / "manuscript"
MS_DIR.mkdir(exist_ok=True)
API = "https://www.ncei.noaa.gov/access/paleo-search/study/search.json"


def fetch_study(study_id: str) -> dict:
    r = requests.get(API, params={"NOAAStudyId": study_id}, timeout=60)
    r.raise_for_status()
    j = r.json()
    studies = j.get("study", [])
    if not studies:
        return {}
    st = studies[0]
    inv = st.get("investigators", "") or "; ".join(
        f"{p.get('lastName', '')}, {p.get('firstName', '')}".strip(", ") for p in st.get("investigatorDetails", []))
    doi = st.get("doi", "")
    if not doi:
        for d in st.get("dataPublisher", []) if isinstance(st.get("dataPublisher"), list) else []:
            doi = doi or d.get("doi", "")
    return {"study_id": study_id, "title": st.get("studyName", ""), "investigators": inv,
            "doi": doi, "contribution_date": st.get("contributionDate", ""),
            "online_link": st.get("onlineResourceLink", "")}


def harvard_authors(inv: str) -> str:
    """'Davi, N.K.; D'Arrigo, R.D.; ...' -> 'Davi, N.K., D'Arrigo, R.D., ...' (drop ORCID parentheses)."""
    parts = [re.sub(r"\(https?://orcid\.org/[^)]*\)", "", p).strip() for p in inv.split(";") if p.strip()]
    return ", ".join(parts)


def main():
    sites = pd.read_parquet(DATA_DIR / "site_metadata.parquet")
    if "landing_page" not in sites.columns:
        sys.exit("site_metadata.parquet has no landing_page column (run 001 in real mode)")
    rows = []
    for _, s in sites.iterrows():
        m = re.search(r"study/(\d+)", str(s["landing_page"]))
        if not m:
            continue
        sid = m.group(1)
        try:
            meta = fetch_study(sid)
        except Exception as e:
            meta = {"study_id": sid, "title": "", "investigators": "", "doi": "", "contribution_date": "", "error": str(e)}
        meta["site_id"] = s["site_id"]
        rows.append(meta)
        print(f"  {s['site_id']:>8} study {sid}: {meta.get('title', '')[:60]} | DOI {meta.get('doi', '') or '?'} | "
              f"contributed {meta.get('contribution_date', '') or '?'}")
    df = pd.DataFrame(rows)
    df.to_csv(MS_DIR / "itrdb_dataset_citations.csv", index=False)
    today = date.today().strftime("%-d %B %Y")
    lines = ["# ITRDB dataset citations (auto-generated by 010 from NOAA metadata; verify once, then paste into references)", ""]
    for _, r in df.sort_values("site_id").iterrows():
        year = (r.get("contribution_date") or "")[:4] or "【year】"
        auth = harvard_authors(r.get("investigators", "")) or "【originators】"
        title = r.get("title") or "【title】"
        doi = re.sub(r"^https?://doi\.org/", "", r.get("doi") or "")
        link = f"https://doi.org/{doi}" if doi else f"https://www.ncei.noaa.gov/access/paleo-search/study/{r['study_id']}"
        lines.append(f"{auth}, {year}. [dataset] {title}. NOAA National Centers for Environmental Information. {link} (accessed {today}).")
        lines.append("")
    (MS_DIR / "itrdb_dataset_citations.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"  wrote {MS_DIR / 'itrdb_dataset_citations.md'} and .csv")
    print("Done.")


if __name__ == "__main__":
    sys.exit(main())
